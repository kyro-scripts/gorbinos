"""Level authoring kit for Gorbino's Quest.

Levels are carved into a character grid with coordinate-based helpers and
emitted as GDScript (scripts/levels/<name>.gd, const DATA := {...}).
A top-down preview PNG is written next to the tools for review.

Grid: x = column (east), y = row (south). One cell = 2 m in game.
"""
import os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENTITY = set("@gyrbpksfZ+hM*AViIcCoOeEB23456RUYxlTtm!XqQwW")


class Color:
    def __init__(self, r, g, b, a=1.0):
        self.v = (r, g, b, a)

    def gd(self):
        return "Color(%s, %s, %s, %s)" % tuple(_num(x) for x in self.v)


def _num(x):
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, int):
        return str(x)
    return repr(float(x))


def to_gd(v, indent=1):
    pad = "\t" * indent
    if isinstance(v, Color):
        return v.gd()
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return _num(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(to_gd(x, indent) for x in v) + "]"
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            items.append("%s%s: %s" % (pad + "\t", to_gd(str(k)), to_gd(x, indent + 1)))
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    raise TypeError(type(v))


class Map:
    def __init__(self, w, h, fill="%"):
        self.w, self.h = w, h
        self.g = [[fill] * w for _ in range(h)]

    def put(self, x, y, ch):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = ch
        else:
            raise IndexError((x, y))

    def get(self, x, y):
        return self.g[y][x]

    def rect(self, x0, y0, x1, y1, ch):
        for y in range(min(y0, y1), max(y0, y1) + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                self.put(x, y, ch)

    def box(self, x0, y0, x1, y1, wall, floor):
        """walls on the border, floor inside (inclusive coords)."""
        self.rect(x0, y0, x1, y1, wall)
        self.rect(x0 + 1, y0 + 1, x1 - 1, y1 - 1, floor)

    def hline(self, x0, x1, y, ch):
        self.rect(x0, y, x1, y, ch)

    def vline(self, x, y0, y1, ch):
        self.rect(x, y0, x, y1, ch)

    def puts(self, x, y, s):
        for i, ch in enumerate(s):
            if ch != " ":
                self.put(x + i, y, ch)

    def stamp(self, x, y, rows):
        """Paste a small ASCII block; spaces are transparent."""
        for j, row in enumerate(rows):
            self.puts(x, y + j, row)

    def scatter(self, x0, y0, x1, y1, ch, n, seed, on=None):
        import random
        r = random.Random(seed)
        placed = 0
        tries = 0
        while placed < n and tries < 5000:
            tries += 1
            x, y = r.randint(x0, x1), r.randint(y0, y1)
            if on is None or self.g[y][x] in on:
                self.put(x, y, ch)
                placed += 1

    def text(self):
        return "\n".join("".join(r) for r in self.g)

    def count(self, chars):
        return sum(1 for r in self.g for c in r if c in chars)


def emit(name, meta, legend, m):
    for k in legend:
        if k in '\\"':
            raise ValueError("legend char %r breaks GDScript strings" % k)
        if k in ENTITY:
            raise ValueError("legend char %r collides with an entity char" % k)
    # every char used must be in the legend or an entity
    used = set(c for r in m.g for c in r)
    unknown = [c for c in used if c not in legend and c not in ENTITY and c != " "]
    if unknown:
        raise ValueError("chars not in legend: %r" % unknown)
    d = dict(meta)
    d["legend"] = legend
    body = to_gd(d, 0)
    # inject the map as a raw multi-line string
    body = body[:-2] + ',\n\t"map": """\n' + m.text() + '\n""",\n}'
    path = os.path.join(ROOT, "scripts", "levels", name + ".gd")
    with open(path, "w") as f:
        f.write("extends RefCounted\n## Generated by tools/levels/%s.py - edit the generator, not this file.\n\n" % name)
        f.write("const DATA := " + body + "\n")
    preview(name, legend, m)
    ents = {}
    for r in m.g:
        for c in r:
            if c in ENTITY and c not in legend:
                ents[c] = ents.get(c, 0) + 1
    print(name, "%dx%d" % (m.w, m.h), "entities:", dict(sorted(ents.items())))


def preview(name, legend, m, scale=12):
    im = Image.new("RGB", (m.w * scale, m.h * scale), (0, 0, 0))
    d = ImageDraw.Draw(im)
    for y in range(m.h):
        for x in range(m.w):
            c = m.g[y][x]
            e = legend.get(c)
            if c in ENTITY and c not in legend:
                col = (255, 255, 255)
            elif e is None:
                col = (0, 0, 0)
            elif e.get("solid") or ("wall" in e and "door" not in e):
                col = (90, 40, 90) if not e.get("use") else (255, 200, 0)
            elif "door" in e:
                col = (255, 120, 0) if not e.get("key") else {"red": (255, 0, 0), "blue": (0, 80, 255), "yellow": (255, 255, 0)}[e["key"]]
                if e.get("secret_door"):
                    col = (255, 0, 255)
            elif "lift" in e:
                col = (0, 255, 255)
            elif e.get("liquid"):
                col = (60, 200, 60)
            else:
                f = float(e.get("floor", 0.0))
                base = 70 + int(f * 30)
                col = (base, base, min(255, base + 40)) if e.get("ctex") != "SKY" else (base, min(255, base + 40), base)
                if e.get("secret"):
                    col = (180, 0, 180)
            d.rectangle([x * scale, y * scale, x * scale + scale - 1, y * scale + scale - 1], fill=col)
            if c in ENTITY and c not in legend:
                d.text((x * scale + 2, y * scale), c, fill=(0, 0, 0))
    out = os.path.join(ROOT, "tools", "previews")
    os.makedirs(out, exist_ok=True)
    im.save(os.path.join(out, name + ".png"))
